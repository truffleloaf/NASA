#!/usr/bin/env node
// Generate lib/data-types.ts from schema/data-contract.schema.json.
// Usage: node scripts/generate-types.mjs [--check]
// The generator supports the same small JSON Schema subset as scripts/contract.py.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA_PATH = path.join(ROOT, "schema", "data-contract.schema.json");
const OUTPUT_PATH = path.join(ROOT, "lib", "data-types.ts");

const schema = JSON.parse(fs.readFileSync(SCHEMA_PATH, "utf8"));
const defs = schema.$defs ?? {};

function definitionName(ref) {
  const match = /^#\/\$defs\/([A-Za-z0-9_-]+)$/.exec(ref ?? "");
  if (!match || !defs[match[1]]) throw new Error(`Unsupported $ref: ${ref}`);
  return defs[match[1]].title;
}

function literal(value) {
  if (Array.isArray(value)) return `[${value.map(literal).join(", ")}]`;
  return JSON.stringify(value);
}

function propertyName(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function arrayType(node, indent) {
  const prefix = node.prefixItems ?? [];
  if (prefix.length) {
    const fixed = prefix.map((item) => typeOf(item, indent));
    if (node.items === undefined || node.items === false) return `[${fixed.join(", ")}]`;
    return `[${fixed.join(", ")}, ...${typeOf(node.items, indent)}[]]`;
  }
  if (node.items === undefined || node.items === true) return "unknown[]";
  return `${typeOf(node.items, indent)}[]`;
}

function objectType(node, indent) {
  const properties = node.properties ?? {};
  const required = new Set(node.required ?? []);
  const entries = Object.entries(properties).map(([name, child]) => {
    const optional = required.has(name) ? "" : "?";
    return `${indent}  ${propertyName(name)}${optional}: ${typeOf(child, `${indent}  `)};`;
  });
  if (node.additionalProperties === false) {
    // no index signature
  } else if (node.additionalProperties && typeof node.additionalProperties === "object") {
    entries.push(`${indent}  [key: string]: ${typeOf(node.additionalProperties, `${indent}  `)};`);
  } else {
    entries.push(`${indent}  [key: string]: unknown;`);
  }
  if (!entries.length) return "Record<string, unknown>";
  return `{\n${entries.join("\n")}\n${indent}}`;
}

function memberType(child, indent) {
  const text = typeOf(child, indent);
  return text.includes(" | ") || text.includes(" & ") ? `(${text})` : text;
}

function typeOf(node, indent = "") {
  if (node === true) return "unknown";
  if (node === false) return "never";
  if (node.$ref) return definitionName(node.$ref);
  if (Object.hasOwn(node, "const")) return literal(node.const);
  if (node.enum) return node.enum.map(literal).join(" | ");
  if (node.oneOf) return node.oneOf.map((child) => memberType(child, indent)).join(" | ");
  if (node.anyOf) return node.anyOf.map((child) => memberType(child, indent)).join(" | ");
  if (node.allOf) return node.allOf.map((child) => memberType(child, indent)).join(" & ");
  if (Array.isArray(node.type)) {
    return node.type.map((name) => typeOf({ ...node, type: name }, indent)).join(" | ");
  }
  switch (node.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return arrayType(node, indent);
    case "object":
      return objectType(node, indent);
    default:
      if (node.properties || node.additionalProperties !== undefined) return objectType(node, indent);
      throw new Error(`Cannot express schema node: ${JSON.stringify(node).slice(0, 160)}`);
  }
}

for (const definition of Object.values(defs)) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(definition.title ?? "")) {
    throw new Error(`Definition title must be a TypeScript identifier: ${definition.title}`);
  }
}

const siteIds = Array.isArray(defs.siteId?.enum) ? defs.siteId.enum : null;

const generated = [
  "// Generated by scripts/generate-types.mjs from schema/data-contract.schema.json.",
  "// Do not edit by hand; run `npm run types:data` after changing the schema.",
  "",
  ...Object.keys(defs).map((name) => `export type ${defs[name].title} = ${typeOf(defs[name])};`),
  ...(siteIds
    ? ["", `export const SITE_IDS = ${literal(siteIds)} as const;`]
    : []),
  "",
].join("\n");

const check = process.argv.includes("--check");
if (check) {
  const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, "utf8") : "";
  // Compare in LF form: a Windows checkout with core.autocrlf=true stores this
  // file with CRLF, which is not a contract drift and must not fail `npm test`.
  if (current.replace(/\r\n/g, "\n") !== generated) {
    console.error("lib/data-types.ts is out of date. Run `npm run types:data`.");
    process.exit(1);
  }
  console.log(`Contract types are current (${Object.keys(defs).length} definitions).`);
} else {
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, generated);
  console.log(`Wrote ${path.relative(ROOT, OUTPUT_PATH)} (${Object.keys(defs).length} definitions).`);
}
